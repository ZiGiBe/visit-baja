    <h3><span>Project summary:</span></h3>
    <p>
        The aim of the project is to build memories for the present and the
        future. Within this framework, we enrich the lives of people living in
        Bácska or visiting us with adult and children's programs and with
        presenting the results of research related to 20th-century modern and
        contemporary art. We provide a unique and fascinating insight and
        discounts into the contemporary world of Bačka by developing our city
        loyalty card system that promotes our collections, exhibitions,
        publications, research, education and cultural programs, and we
        highlight topics through the lens of modern and contemporary art that
        affect our society and our individual lives.
    </p>
    <p>
        Our interactions between the public and art are driven by dialogues with
        artists. The complex topics of yesterday, today and tomorrow - defined
        by artists and indicated by ourselves - are explored within the project.
        This vision is driven by a fresh, energetic approach to the
        collaborative presentation, care and renewal of our special art
        collections. The purpose of the loyalty city card promoting the results
        of the project is to increase the cultural and tourist status of the CBR
        among the residents, visitors and businesses. We would like to
        contribute to the livability, cultural appeal and well-being of the
        sustainably developing and inclusive Bácska region by organizing
        high-quality professional cultural and heritage protection cooperation,
        programs and events in which we involve the micro- and macro-society of
        the region, local businesses and visitors to the region in an efficient
        and controlled manner. To this end, 4 organizations, the Szabadka City
        Museum, the Baja Tourism Organization and the Temerin municipality,
        under the leadership of the István Türr Museum and Bácska Cultural
        Center, have put together a coordinated and very rich cultural
        entertainment and cultural education program, which will be jointly
        implemented over 2 years.
    </p>
    <p>
        We also complete the Temerin castle complex with the revitalization of
        the castle park, the creation of the open-air modern and contemporary
        sculpture park demonstrating the harmony of nature and art, as a real
        gem of South-Bácska it impresses not only local residents but domestic
        and foreign tourism alike.
    </p>
    <p>
        The project partners want to join the Bácska region with its important
        settlements: Baja, Szabadka and Temerin to the European scientific,
        cultural and artistic circulation and make it better known for domestic
        and international tourism by researching Bácska's 20th-century and
        contemporary arts, by collecting, preserving, processing and presenting
        their cultural resources, tangible and intangible cultural heritage,
        presenting their specific modern and contemporary artistic values,
        exhibitions, publications, cultural events and museum education
        programs.
    </p>
