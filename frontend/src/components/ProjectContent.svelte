    <h3><span>Projekt leírása:</span></h3>
    <p>
        A projekt célja a jelen és a jövő emlékeinek építése. Ennek keretében
        felnőtt- és gyermekprogramokkal, valamint a 20. századi modern és
        kortárs művészethez kapcsolódó kutatási eredmények bemutatásával
        gazdagítjuk a Bácskában élők vagy hozzánk látogatók életét.
        Gyűjteményeinket, kiállításainkat, kiadványainkat, kutatásainkat,
        oktatási és kulturális programjainkat népszerűsítő városi törzsvásárlói
        kártyarendszer fejlesztésével egyedülálló kedvezményeket és lenyűgöző
        betekintést biztosítunk Bácska kortárs világába. A társadalmunkra és
        egyéni életünkre nagy hatást gyakorló modern és kortárs művészet
        szemüvegén keresztül mutatjuk be a különböző témákat.
    </p>
    <p>
        A nyilvánosság és a művészet közötti kölcsönös kapcsolatot a művészekkel
        folytatott párbeszédek vezérlik. A művészek által meghatározott, de
        általunk megjelölt tegnap, ma és holnap összetett témái kerülnek
        feltárásra a projektben. Ezt a jövőképet a különleges művészeti
        gyűjteményeink közös bemutatásának, gondozásának és megújításának friss,
        újszerű megközelítése vezérli. A projekt eredményeit népszerűsítő
        hűség-városi kártya célja a határmenti régió kulturális és turisztikai
        státuszának növelése a lakosság, a látogatók és a vállalkozások körében.
    </p>
    <p>
        A fenntarthatóan fejlődő és befogadó bácskai térség kulturális
        vonzerejéhez és boldogulásához kívánunk hozzájárulni magas színvonalú
        szakmai, kulturális és örökségvédelmi együttműködések, programok,
        rendezvények szervezésével, amelyekbe bevonjuk az ország mikro- és
        makrotársadalmát, a régiót, a helyi vállalkozásokat és a régióba
        látogatókat hatékonyan és ellenőrzött módon. Ennek érdekében négy
        szervezet, a Szabadkai Városi Múzeum, a Bajai Turisztikai Szervezet és
        Temerin Város Önkormányzata a Türr István Múzeum és Bácskai Kulturális
        Központ vezetésével összehangolt és igen gazdag kulturális szórakoztató
        és kulturális oktatási programot állított össze, amelyet két éven
        keresztül közösen valósítanak meg. A temerini kastélyegyüttest is
        kiegészítjük a kastélypark revitalizálásával, a szabadtéri modern és
        kortárs szoborpark létrehozásával, amely a természet és a művészet
        harmóniáját demonstrálja, Dél-Bácska igazi gyöngyszemeként nemcsak a
        helyi lakosokat nyűgözi le, hanem a belföldi és külföldi turizmust
        egyaránt. A projektpartnerek a Bácska térséget fontos településeivel:
        Bajával, Szabadkával és Temerinnel az európai tudományos, kulturális és
        művészeti vérkeringésbe kívánják bekapcsolni, valamint Bácska 20.
        századi és kortárs művészetének kutatásával, gyűjtéssel ismertebbé tenni
        a hazai és nemzetközi turizmusban kulturális erőforrásaik, tárgyi és
        szellemi kulturális örökségük megőrzése, feldolgozása és bemutatása,
        sajátos modern és kortárs művészeti értékeik bemutatása, kiállítások,
        kiadványok, kulturális rendezvények, múzeumpedagógiai programok által.
    </p>
